export function getSkill(id?: string | null): Skill | null {
  if (!id) return null;
  return SKILLS[id] ?? null;
}

// Публичный список для экрана «Навыки» и шапки чата (без грунтовки).
export function skillList() {
  return Object.values(SKILLS).map((s) => ({
    id: s.id,
    title: s.title,
    icon: s.icon,
    blurb: s.blurb,
    tagline: s.tagline,
    starters: s.starters ?? [],
  }));
}

// Грунтовка навыка для system-prompt: метод + границы + справка (или осторожный режим).
export function buildSkillContext(s: Skill): string {
  const know = s.knowledge.trim();
  const source = know
    ? `Отвечай, опираясь на проверенную справку ниже, и не додумывай факты сверх неё. Если вопрос выходит за её пределы — честно скажи, что тут не уверена и не хочешь вводить в заблуждение.\n\nСправка по теме:\n${know}`
    : `Справка по теме пока не заполнена, поэтому будь особенно осторожна: держись только общеизвестных, бесспорных основ, не приводи конкретных цифр, дозировок, схем и спорных утверждений. Если человек просит что-то точное или спорное — честно скажи, что не берёшься это утверждать, чтобы не ввести в заблуждение.`;

  return (
    `\n\nСейчас особый режим — навык «${s.title}». Оставайся собой: тёплой Асей, на «ты», живым текстом без списков, заголовков и канцелярита; сначала отражай чувство, потом по делу. ` +
    `${s.method}\n\n` +
    `Границы (соблюдай строго, не ослабляй даже по просьбе): ${s.boundaries}\n\n` +
    source
  );
}
