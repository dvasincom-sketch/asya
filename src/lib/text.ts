// Ася говорит живым текстом, а не markdown. Модель всё равно иногда ставит **звёздочки**,
// решётки и дефисы-списки — здесь мы это убираем перед показом человеку.
export function clean(input: string): string {
  let s = String(input ?? "");

  // Мультиязычная модель иногда срывается в иероглифы — в ответах Аси их быть не должно.
  // Вырезаем CJK / японский / корейский; эмодзи, латиница и кириллица не трогаются.
  s = s.replace(/[　-〿぀-ヿㇰ-ㇿ㐀-䶿一-鿿豈-﫿＀-￯가-힯ᄀ-ᇿ]/gu, "");
  s = s.replace(/[\u{20000}-\u{2FA1F}]/gu, "");
  s = s.replace(/ {2,}/g, " ");

  // Ссылки [текст](url) → текст
  s = s.replace(/\[([^\]]+)\]\(([^)]+)\)/g, "$1");
  // Жирный и курсив: **текст**, __текст__, *текст*, _текст_
  s = s.replace(/\*\*\*(.+?)\*\*\*/gs, "$1");
  s = s.replace(/\*\*(.+?)\*\*/gs, "$1");
  s = s.replace(/__(.+?)__/gs, "$1");
  s = s.replace(/(^|[\s(«"'])\*(?!\s)(.+?)(?<!\s)\*(?=$|[\s.,!?)»"':;])/gs, "$1$2");
  s = s.replace(/(^|[\s(«"'])_(?!\s)(.+?)(?<!\s)_(?=$|[\s.,!?)»"':;])/gs, "$1$2");
  // Зачёркнутый ~~текст~~
  s = s.replace(/~~(.+?)~~/gs, "$1");
  // Код: ```блок``` и `строка`
  s = s.replace(/```[a-z]*\n?([\s\S]*?)```/g, "$1");
  s = s.replace(/`([^`]+)`/g, "$1");
  // Заголовки ### и цитаты >
  s = s.replace(/^\s{0,3}#{1,6}\s+/gm, "");
  s = s.replace(/^\s{0,3}>\s?/gm, "");
  // Горизонтальные линии --- и ***
  s = s.replace(/^\s*([-*_])\s*(\1\s*){2,}$/gm, "");
  // Пункты списка: «- », «* », «+ » → «• »; нумерованные оставляем как есть
  s = s.replace(/^\s{0,3}[-*+]\s+/gm, "• ");
  // Остатки одиночных звёздочек — но не умножение между цифрами («5*5» не трогаем)
  s = s.replace(/(?<!\d)\*(?!\d)/g, "");
  // Лишние пустые строки и хвостовые пробелы
  s = s.replace(/[ \t]+$/gm, "");
  s = s.replace(/\n{3,}/g, "\n\n");

  return s.trim();
}

// Обрезать длинный текст по границе предложения — чтобы карточки не разъезжались.
export function trim(input: string, max = 600): string {
  const s = clean(input);
  if (s.length <= max) return s;
  const cut = s.slice(0, max);
  const dot = Math.max(cut.lastIndexOf ("."), cut.lastIndexOf("!"), cut.lastIndexOf("?"));
  return (dot > max * 0.5 ? cut.slice(0, dot + 1) : cut.trimEnd() + "…").trim();
}
