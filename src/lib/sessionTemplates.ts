export function getTemplate(id: string): SessionTemplate | null {
  return TEMPLATES[id] ?? null;
}

// Публичный список для экрана выбора (без вопросов — каркас остаётся невидимым).
export function templateList() {
  return Object.values(TEMPLATES).map((t) => ({
    id: t.id,
    title: t.title,
    icon: t.icon,
    group: t.group,
    blurb: t.blurb,
    badge: t.badge,
    steps: t.questions.length,
  }));
}
