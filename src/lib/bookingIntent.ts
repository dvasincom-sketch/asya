// Понимаем, когда человек правда хочет записаться. Карточку записи показываем
// только по явному запросу — Ася прежде всего подружка, а не продавец.

// Явное желание записаться / прийти / забронировать.
const EXPLICIT =
  /(запиш[иь]|записать(ся)?|запишусь|записаться|хочу\s+запис|можно\s+запис|забронир|брониров|взять\s+окош|свободн\w*\s+(врем|окош|слот)|есть\s+окош|когда\s+можно\s+прий|прийти\s+в\s+салон|приехать\s+в\s+салон)/i;

// Упоминание самой услуги/салона рядом с желанием («хочу на массаж головы»).
const SERVICE = /(хедспа|хэдспа|head\s?spa|headspa|массаж\s+головы|спа[\s-]?процедур|уход\s+за\s+волос|в\s+салон)/i;
const WANT = /(хочу|хочется|мечтаю|надо\s+бы|давай|можно|как\s+бы)/i;

// Явный отказ — чтобы не навязываться повторно.
const DECLINE = /(не\s+хочу|не\s+надо|потом|позже|не\s+сейчас|не\s+интересно)/i;

export function wantsBooking(text: string): boolean {
  const t = (text || "").toLowerCase();
  if (!t) return false;
  if (DECLINE.test(t)) return false;
  if (EXPLICIT.test(t)) return true;
  return SERVICE.test(t) && WANT.test(t);
}
