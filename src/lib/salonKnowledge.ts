// Похоже, что человек спрашивает про программы, а не просто беседует.
const ASKS =
  /(чем\s+отлич|в\s+чём\s+разниц|что\s+входит|что\s+лучше|что\s+выбрать|посовету|сколько\s+сто|цена|стоимость|сколько\s+по\s+времени|длительн|сколько\s+идёт|как\s+долго|что\s+за\s+программ|расскажи\s+про\s+программ|какие\s+(есть\s+)?(программ|услуг))/i;

export function mentionsProgram(text: string): boolean {
  const t = (text || "").toLowerCase();
  return PROGRAMS.some((p) => p.aliases.some((a) => t.includes(a)));
}

export function asksAboutServices(text: string): boolean {
  const t = (text || "").toLowerCase();
  if (mentionsProgram(t)) return true;
  const salonish = /(хедспа|хэдспа|head\s?spa|салон|массаж\s+головы|спа|процедур)/i.test(t);
  return salonish && ASKS.test(t);
}

// Компактная справка для system-prompt — только когда человек про это спросил.
export function buildProgramsContext(): string {
  const list = PROGRAMS.map((p) => {
    const inc = p.includes.length ? ` Что входит: ${p.includes.join("; ")}.` : "";
    return `${p.name} — ${p.duration}, ${p.price}. Суть: ${p.essence}.${inc} Кому: ${p.forWhom}.`;
  }).join("\n");

  return (
    "\n\nЧто ты знаешь о программах салона HeadSPA Beauty (отвечай ТОЛЬКО по этим данным, ничего не додумывай; " +
    "если человек спрашивает о программе, которой здесь нет — честно скажи, что уточнишь у мастера, и предложи записаться; " +
    "рассказывай своими словами, тепло и коротко, без списков и прайс-листов, называй цену и длительность только если спросили):\n" +
    list +
    "\nЕсли где-то написано «уточняется» или состав не указан — не придумывай его, а скажи, что подробности лучше уточнить у мастера, " +
    "и предложи записаться. Если человек говорит просто «гималайский» — мягко уточни, имеет он в виду «Дзен» или «Экспресс»."
  );
}
