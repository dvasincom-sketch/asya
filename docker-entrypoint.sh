#!/bin/sh
# Старт приложения. База могла ещё просыпаться после перезапуска — даём ей несколько попыток,
# но в любом случае поднимаем сервер: страницы и /api/health не должны падать из-за БД.

i=1
max=5
while [ "$i" -le "$max" ]; do
  if npx prisma migrate deploy; then
    echo "[start] Миграции применены."
    break
  fi
  echo "[start] База недоступна (попытка $i из $max). Ждём 5 секунд…"
  i=$((i + 1))
  [ "$i" -le "$max" ] && sleep 5
done

if [ "$i" -gt "$max" ]; then
  echo "[start] ВНИМАНИЕ: применить миграции не удалось — база недоступна."
  echo "[start] Приложение всё равно запускается: то, что не требует БД, будет работать."
  echo "[start] Миграции применятся автоматически при следующем перезапуске контейнера."
fi

exec npm run start
