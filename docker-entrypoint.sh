#!/bin/sh
# Цель: сервер должен НАЧАТЬ СЛУШАТЬ порт сразу, чтобы health-check (/api/health — без БД)
# проходил мгновенно. Иначе, пока миграции ждут просыпающуюся базу, оркестратор считает
# контейнер «мёртвым» и убивает его (SIGTERM-луп на каждом деплое).
#
# Стратегия: одна быстрая синхронная попытка миграций (обычный деплой — база на месте,
# схема применится до трафика). Если база недоступна — миграции уходят в ФОН с длинными
# ретраями, а сервер поднимается немедленно. Всё, что не требует БД, работает; запросы к БД
# мягко деградируют (withDb/кеш), а миграции применяются, как только база встанет.

run_migrations_bg() {
  i=1
  max=30            # до ~5 минут (30 × 10с) — покрывает окно недоступности БД после деплоя
  while [ "$i" -le "$max" ]; do
    if npx prisma migrate deploy; then
      echo "[migrate] Миграции применены в фоне (попытка $i)."
      return 0
    fi
    echo "[migrate] База недоступна (фон, попытка $i из $max). Ждём 10 секунд…"
    i=$((i + 1))
    [ "$i" -le "$max" ] && sleep 10
  done
  echo "[migrate] ВНИМАНИЕ: миграции не применены — база долго недоступна. Применятся при следующем старте."
  return 1
}

# Быстрая синхронная попытка (fail-fast: при недоступной БД prisma отдаёт P1001 за секунды).
if npx prisma migrate deploy; then
  echo "[migrate] Миграции применены синхронно на старте."
else
  echo "[migrate] База недоступна — не блокируем старт, миграции уходят в фон."
  run_migrations_bg &
fi

# Сервер поднимается сразу и держит health-check, пока база просыпается.
exec npm run start
